export interface WafMatch {
  name: string;
  kind: string;
  confidence: "High" | "Medium";
  evidence: { kind: string; value: string }[];
}

export function detectWaf(headers: Headers, body: string, cnames: string[] = []): WafMatch[] {
  const out: WafMatch[] = [];
  const headerDump: Record<string, string> = {};
  headers.forEach((v, k) => (headerDump[k.toLowerCase()] = v));
  const cookie = headers.get("set-cookie") ?? Object.entries(headerDump).filter(([k]) => k === "set-cookie").map(([, v]) => v).join("; ");
  const server = headers.get("server") ?? "";
  for (const sig of WAF_SIGS) {
    const ev: { kind: string; value: string }[] = [];
    if (sig.server && sig.server.test(server)) ev.push({ kind: "Header", value: `server: ${server}` });
    if (sig.headerName && headerDump[sig.headerName]) ev.push({ kind: "Header", value: `${sig.headerName}: ${headerDump[sig.headerName].slice(0, 60)}` });
    if (sig.cookie && sig.cookie.test(cookie)) ev.push({ kind: "Cookie", value: (cookie.match(sig.cookie)?.[0] ?? "").slice(0, 40) });
    if (sig.body && sig.body.test(body)) ev.push({ kind: "Block page", value: (body.match(sig.body)?.[0] ?? "").slice(0, 60) });
    if (sig.cname && cnames.some((c) => sig.cname!.test(c))) ev.push({ kind: "CNAME", value: cnames.find((c) => sig.cname!.test(c)) ?? "" });
    if (ev.length) out.push({ name: sig.name, kind: sig.kind, confidence: ev.length >= 2 || ev.some((e) => e.kind === "Block page") ? "High" : "Medium", evidence: ev });
  }
  return out;
}
