// Technology and WAF/CDN fingerprinting shared by HTTP Fingerprint, WAF and Full Scan.

export function detectTech(headers: Headers, body: string): string[] {
  const t = new Set<string>();
  const server = headers.get("server") ?? "";
  const serverSigs: [RegExp, string][] = [
    [/nginx/i, "nginx"],
    [/apache/i, "Apache"],
    [/microsoft-iis/i, "Microsoft IIS"],
    [/litespeed/i, "LiteSpeed"],
    [/openresty/i, "OpenResty"],
    [/caddy/i, "Caddy"],
  ];
  for (const [re, n] of serverSigs) if (re.test(server)) t.add(n);
  if (headers.get("cf-ray") || /cloudflare/i.test(server)) t.add("Cloudflare");
  if (headers.get("x-vercel-id")) t.add("Vercel");
  if (headers.get("x-amz-cf-id") || /cloudfront/i.test(headers.get("via") ?? "")) t.add("Amazon CloudFront");
  if (/AmazonS3/i.test(server)) t.add("Amazon S3");
  if (headers.get("x-github-request-id")) t.add("GitHub Pages");
  if (headers.get("x-fastly-request-id") || /fastly/i.test(server)) t.add("Fastly");
  if (headers.get("x-akamai-transformed") || /akamai/i.test(server)) t.add("Akamai");
  const xp = headers.get("x-powered-by");
  if (xp) t.add(xp);
  const bodySigs: [RegExp, string][] = [
    [/wp-content|wp-includes|wp-json/i, "WordPress"],
    [/Joomla!/i, "Joomla"],
    [/Drupal\.settings|\/sites\/default\/files/i, "Drupal"],
    [/__NEXT_DATA__|\/_next\/static/i, "Next.js"],
    [/__NUXT__|\/_nuxt\//i, "Nuxt"],
    [/data-reactroot|react-dom/i, "React"],
    [/ng-version=/i, "Angular"],
    [/vue(\.min)?\.js|data-v-[0-9a-f]{8}/i, "Vue"],
    [/cdn\.shopify\.com/i, "Shopify"],
    [/static\.wixstatic\.com/i, "Wix"],
    [/squarespace/i, "Squarespace"],
    [/jquery[.-]/i, "jQuery"],
    [/bootstrap(\.min)?\.(css|js)/i, "Bootstrap"],
    [/googletagmanager\.com/i, "Google Tag Manager"],
    [/google-analytics\.com|gtag\(|G-[A-Z0-9]{8,}/i, "Google Analytics"],
    [/hotjar/i, "Hotjar"],
    [/recaptcha/i, "reCAPTCHA"],
    [/cloudflareinsights/i, "Cloudflare Analytics"],
  ];
  for (const [re, n] of bodySigs) if (re.test(body)) t.add(n);
  const gen = body.match(/<meta[^>]+name=["']generator["'][^>]+content=["']([^"']+)/i)?.[1];
  if (gen) t.add(gen);
  return [...t];
}

